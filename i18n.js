  const months = ['ýanwar','fewral','mart','aprel','maý','iýun','iýul','awgust','sentýabr','oktýabr','noýabr','dekabr'];
  let text = `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
